/**
 * Exporters for Adobe Swatch Exchange (.ASE), 3D LUT (.CUBE), and Lightroom Presets (.XMP)
 */

import { hexToRgb, rgbToHsl } from './colorMath';

export interface SwatchItem {
  name: string;
  hex: string;
}

export interface ColorRecipe {
  id: string;
  name: string;
  category: string;
  harmonyType: string;
  swatches: SwatchItem[]; // e.g. Key (60%), Secondary (30%), Accent (10%)
  description?: string;
  createdAt: string;
}

/**
 * Builds an Adobe Swatch Exchange (.ase) binary ArrayBuffer
 */
export function generateAseBuffer(recipeName: string, swatches: SwatchItem[]): Uint8Array {
  // Calculate buffer size
  // Header: 'ASEF' (4 bytes) + version (4 bytes) + numBlocks (4 bytes) = 12 bytes
  let totalSize = 12;

  // Each swatch:
  // blockType (2 bytes) + blockLength (4 bytes)
  // nameLength (2 bytes) + (name.length + 1) * 2 bytes UTF-16BE
  // colorModel 'RGB ' (4 bytes)
  // 3 * 4 bytes float (12 bytes)
  // colorType (2 bytes)
  const swatchBlocksData: { nameChars: number[]; r: number; g: number; b: number }[] = [];

  for (const sw of swatches) {
    const rgb = hexToRgb(sw.hex);
    const chars: number[] = [];
    for (let i = 0; i < sw.name.length; i++) {
      chars.push(sw.name.charCodeAt(i));
    }
    chars.push(0); // null termination

    const blockContentLength = 2 + (chars.length * 2) + 4 + 12 + 2;
    totalSize += 6 + blockContentLength;

    swatchBlocksData.push({
      nameChars: chars,
      r: rgb.r / 255,
      g: rgb.g / 255,
      b: rgb.b / 255,
    });
  }

  const buffer = new ArrayBuffer(totalSize);
  const view = new DataView(buffer);
  let offset = 0;

  // 'ASEF'
  view.setUint8(offset++, 0x41);
  view.setUint8(offset++, 0x53);
  view.setUint8(offset++, 0x45);
  view.setUint8(offset++, 0x46);

  // Version 1.0 (major = 1, minor = 0)
  view.setUint16(offset, 1, false);
  offset += 2;
  view.setUint16(offset, 0, false);
  offset += 2;

  // Number of blocks
  view.setUint32(offset, swatches.length, false);
  offset += 4;

  for (const sw of swatchBlocksData) {
    // Block type: 0x0001 (Color entry)
    view.setUint16(offset, 1, false);
    offset += 2;

    const blockContentLength = 2 + (sw.nameChars.length * 2) + 4 + 12 + 2;
    view.setUint32(offset, blockContentLength, false);
    offset += 4;

    // Name length (number of UTF-16 characters including null terminator)
    view.setUint16(offset, sw.nameChars.length, false);
    offset += 2;

    for (const code of sw.nameChars) {
      view.setUint16(offset, code, false);
      offset += 2;
    }

    // Color model 'RGB '
    view.setUint8(offset++, 0x52); // 'R'
    view.setUint8(offset++, 0x47); // 'G'
    view.setUint8(offset++, 0x42); // 'B'
    view.setUint8(offset++, 0x20); // ' '

    // 3 x 32-bit floats
    view.setFloat32(offset, sw.r, false);
    offset += 4;
    view.setFloat32(offset, sw.g, false);
    offset += 4;
    view.setFloat32(offset, sw.b, false);
    offset += 4;

    // Color type: 0 (Normal / Process), 1 (Global), 2 (Spot)
    view.setUint16(offset, 0, false);
    offset += 2;
  }

  return new Uint8Array(buffer);
}

/**
 * Generates an industry-standard 3D LUT (.CUBE) file for DaVinci Resolve, Premiere, Photoshop.
 * Creates an expressive 17x17x17 color transform using the recipe's Key and Secondary harmony tones.
 */
export function generateCubeLut(recipe: ColorRecipe): string {
  const size = 17;
  const lines: string[] = [];

  lines.push(`# DaVinci Resolve & Premiere Pro 3D LUT`);
  lines.push(`# Generated by The Ultimate Color Psychology & Cinematography Matrix`);
  lines.push(`TITLE "${recipe.name} (${recipe.category})"`);
  lines.push(`LUT_3D_SIZE ${size}`);
  lines.push(`DOMAIN_MIN 0.0 0.0 0.0`);
  lines.push(`DOMAIN_MAX 1.0 1.0 1.0`);
  lines.push('');

  // Primary swatch (shadows/midtones tone tint) and secondary swatch (highlight tint)
  const s0 = recipe.swatches[0] ? hexToRgb(recipe.swatches[0].hex) : { r: 180, g: 120, b: 80 };
  const s1 = recipe.swatches[1] ? hexToRgb(recipe.swatches[1].hex) : { r: 60, g: 120, b: 160 };

  const tint0 = { r: s0.r / 255, g: s0.g / 255, b: s0.b / 255 };
  const tint1 = { r: s1.r / 255, g: s1.g / 255, b: s1.b / 255 };

  // Loop through 3D Cube (B outer, G middle, R inner per standard .cube format)
  for (let b = 0; b < size; b++) {
    const normB = b / (size - 1);
    for (let g = 0; g < size; g++) {
      const normG = g / (size - 1);
      for (let r = 0; r < size; r++) {
        const normR = r / (size - 1);

        // Luminance
        const lum = 0.2126 * normR + 0.7152 * normG + 0.0722 * normB;

        // Apply cinematic split-toning curve based on the harmony palette
        // Shadows lean toward tint1/tint0, highlights lean toward secondary
        const shadowWeight = Math.pow(Math.max(0, 1 - lum), 1.6) * 0.35;
        const highlightWeight = Math.pow(lum, 1.4) * 0.25;

        let outR = normR + (tint0.r - 0.5) * shadowWeight + (tint1.r - 0.5) * highlightWeight;
        let outG = normG + (tint0.g - 0.5) * shadowWeight + (tint1.g - 0.5) * highlightWeight;
        let outB = normB + (tint0.b - 0.5) * shadowWeight + (tint1.b - 0.5) * highlightWeight;

        // Subtle S-curve contrast
        outR = Math.max(0, Math.min(1, outR));
        outG = Math.max(0, Math.min(1, outG));
        outB = Math.max(0, Math.min(1, outB));

        lines.push(`${outR.toFixed(6)} ${outG.toFixed(6)} ${outB.toFixed(6)}`);
      }
    }
  }

  return lines.join('\n');
}

/**
 * Generates an Adobe Lightroom Classic / ACR .XMP preset with Color Grading wheels & HSL calibrations
 */
export function generateLightroomXmp(recipe: ColorRecipe): string {
  const s0 = recipe.swatches[0] ? hexToRgb(recipe.swatches[0].hex) : { r: 200, g: 140, b: 90 };
  const s1 = recipe.swatches[1] ? hexToRgb(recipe.swatches[1].hex) : { r: 70, g: 130, b: 170 };
  const s2 = recipe.swatches[2] ? hexToRgb(recipe.swatches[2].hex) : { r: 230, g: 190, b: 100 };

  const hsl0 = rgbToHsl(s0.r, s0.g, s0.b);
  const hsl1 = rgbToHsl(s1.r, s1.g, s1.b);
  const hsl2 = rgbToHsl(s2.r, s2.g, s2.b);

  const shadowHue = hsl1.h;
  const shadowSat = Math.min(45, Math.round(hsl1.s * 0.4));
  const highlightHue = hsl0.h;
  const highlightSat = Math.min(45, Math.round(hsl0.s * 0.35));
  const midtoneHue = hsl2.h;
  const midtoneSat = Math.min(30, Math.round(hsl2.s * 0.3));

  return `<?xml version="1.0" encoding="UTF-8"?>
<x:xmpmeta xmlns:x="adobe:ns:meta/" x:xmptk="Adobe XMP Core 7.0-c000 1.000000, 2026/01/01">
 <rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#">
  <rdf:Description rdf:about=""
    xmlns:crs="http://ns.adobe.com/camera-raw-settings/1.0/"
    crs:PresetType="Normal"
    crs:Cluster=""
    crs:UUID="${recipe.id}"
    crs:SupportsAmount="True"
    crs:SupportsColor="True"
    crs:Name="${escapeXml(recipe.name)}"
    crs:Group="Color Psychology Matrix Presets"
    crs:Description="${escapeXml(recipe.description || recipe.harmonyType)}"
    crs:SplitToningShadowHue="${shadowHue}"
    crs:SplitToningShadowSaturation="${shadowSat}"
    crs:SplitToningHighlightHue="${highlightHue}"
    crs:SplitToningHighlightSaturation="${highlightSat}"
    crs:SplitToningBalance="0"
    crs:ColorGradeMidtoneHue="${midtoneHue}"
    crs:ColorGradeMidtoneSat="${midtoneSat}"
    crs:ColorGradeShadowLum="0"
    crs:ColorGradeMidtoneLum="0"
    crs:ColorGradeHighlightLum="0"
    crs:ColorGradeBlending="50"
    crs:ColorGradeGlobalHue="0"
    crs:ColorGradeGlobalSat="0"
    crs:ColorGradeGlobalLum="0"
    crs:HasSettings="True">
  </rdf:Description>
 </rdf:RDF>
</x:xmpmeta>`;
}

function escapeXml(unsafe: string): string {
  return unsafe.replace(/[<>&'"]/g, c => {
    switch (c) {
      case '<': return '&lt;';
      case '>': return '&gt;';
      case '&': return '&amp;';
      case '\'': return '&apos;';
      case '"': return '&quot;';
      default: return c;
    }
  });
}

/**
 * Trigger file download helper
 */
export function downloadFile(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 2000);
}
