/**
 * Google Drive REST API Client for Color Matrix Applet
 * Handles cloud sync of color presets (.cube, .ase, .xmp, .json),
 * asset browsing, and file downloads.
 */

export interface DriveFileItem {
  id: string;
  name: string;
  mimeType: string;
  size?: string;
  modifiedTime?: string;
  webViewLink?: string;
  thumbnailLink?: string;
  iconLink?: string;
}

export interface DriveStorageQuota {
  limit?: string;
  usage?: string;
  usageInDrive?: string;
  user?: {
    displayName?: string;
    emailAddress?: string;
    photoLink?: string;
  };
}

const COLOR_MATRIX_FOLDER_NAME = 'Color Matrix Presets';

/**
 * Finds or creates the default app folder on user's Google Drive
 */
export async function ensurePresetFolder(accessToken: string): Promise<string> {
  const query = `name = '${COLOR_MATRIX_FOLDER_NAME}' and mimeType = 'application/vnd.google-apps.folder' and trashed = false`;
  const searchUrl = `https://www.googleapis.com/drive/v3/files?q=${encodeURIComponent(query)}&fields=files(id,name)`;

  const res = await fetch(searchUrl, {
    headers: { Authorization: `Bearer ${accessToken}` },
  });

  if (!res.ok) {
    throw new Error(`Failed to query Google Drive: ${res.statusText}`);
  }

  const data = await res.json();
  if (data.files && data.files.length > 0) {
    return data.files[0].id;
  }

  // Create folder
  const createRes = await fetch('https://www.googleapis.com/drive/v3/files', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${accessToken}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      name: COLOR_MATRIX_FOLDER_NAME,
      mimeType: 'application/vnd.google-apps.folder',
      description: 'Color palettes, 3D LUTs, and grading presets generated by Color Matrix',
    }),
  });

  if (!createRes.ok) {
    throw new Error(`Failed to create Google Drive folder: ${createRes.statusText}`);
  }

  const newFolder = await createRes.json();
  return newFolder.id;
}

/**
 * Uploads a text or binary file to Google Drive (inside the designated folder or root)
 */
export async function uploadToDrive({
  name,
  content,
  mimeType,
  folderId,
  accessToken,
}: {
  name: string;
  content: string | Blob | Uint8Array;
  mimeType: string;
  folderId?: string;
  accessToken: string;
}): Promise<DriveFileItem> {
  const metadata: Record<string, any> = {
    name,
    mimeType,
  };

  if (folderId) {
    metadata.parents = [folderId];
  }

  const boundary = '-------314159265358979323846';
  const delimiter = `\r\n--${boundary}\r\n`;
  const closeDelimiter = `\r\n--${boundary}--`;

  let body: Blob;

  if (typeof content === 'string') {
    const multipartRequestBody =
      delimiter +
      'Content-Type: application/json; charset=UTF-8\r\n\r\n' +
      JSON.stringify(metadata) +
      delimiter +
      `Content-Type: ${mimeType}\r\n\r\n` +
      content +
      closeDelimiter;

    body = new Blob([multipartRequestBody], { type: `multipart/related; boundary=${boundary}` });
  } else {
    // Binary or Blob content
    const metadataBlob = new Blob([
      delimiter +
      'Content-Type: application/json; charset=UTF-8\r\n\r\n' +
      JSON.stringify(metadata) +
      delimiter +
      `Content-Type: ${mimeType}\r\n\r\n`,
    ], { type: 'text/plain' });

    const endBlob = new Blob([closeDelimiter], { type: 'text/plain' });
    const contentBlob = content instanceof Blob ? content : new Blob([content as unknown as BlobPart], { type: mimeType });

    body = new Blob([metadataBlob, contentBlob, endBlob], { type: `multipart/related; boundary=${boundary}` });
  }

  const uploadUrl = 'https://www.googleapis.com/upload/drive/v3/files?uploadType=multipart&fields=id,name,mimeType,size,modifiedTime,webViewLink';
  const response = await fetch(uploadUrl, {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${accessToken}`,
      'Content-Type': `multipart/related; boundary=${boundary}`,
    },
    body,
  });

  if (!response.ok) {
    const errorText = await response.text();
    throw new Error(`Upload to Google Drive failed (${response.status}): ${errorText}`);
  }

  return await response.json();
}

/**
 * List files from Google Drive
 */
export async function listDriveFiles({
  accessToken,
  folderId,
  searchQuery = '',
  pageSize = 50,
}: {
  accessToken: string;
  folderId?: string;
  searchQuery?: string;
  pageSize?: number;
}): Promise<DriveFileItem[]> {
  const queryParts: string[] = ['trashed = false'];

  if (folderId) {
    queryParts.push(`'${folderId}' in parents`);
  }

  if (searchQuery.trim()) {
    const escapedSearchQuery = searchQuery.trim().replace(/\\/g, '\\\\').replace(/'/g, "\\'");
    queryParts.push(`name contains '${escapedSearchQuery}'`);
  }

  const q = queryParts.join(' and ');
  const url = `https://www.googleapis.com/drive/v3/files?q=${encodeURIComponent(
    q
  )}&pageSize=${pageSize}&orderBy=modifiedTime desc&fields=files(id,name,mimeType,size,modifiedTime,webViewLink,thumbnailLink,iconLink)`;

  const res = await fetch(url, {
    headers: { Authorization: `Bearer ${accessToken}` },
  });

  if (!res.ok) {
    throw new Error(`Failed to list Google Drive files: ${res.statusText}`);
  }

  const data = await res.json();
  return data.files || [];
}

/**
 * Download file content from Google Drive
 */
export async function downloadDriveFile(
  fileId: string,
  accessToken: string
): Promise<{ text?: string; blob: Blob; name: string }> {
  // First get metadata for filename
  const metaRes = await fetch(`https://www.googleapis.com/drive/v3/files/${fileId}?fields=name,mimeType`, {
    headers: { Authorization: `Bearer ${accessToken}` },
  });
  const meta = await metaRes.json();

  const res = await fetch(`https://www.googleapis.com/drive/v3/files/${fileId}?alt=media`, {
    headers: { Authorization: `Bearer ${accessToken}` },
  });

  if (!res.ok) {
    throw new Error(`Failed to download file from Google Drive: ${res.statusText}`);
  }

  const blob = await res.blob();
  let text: string | undefined;

  if (
    meta.mimeType?.includes('text') ||
    meta.mimeType?.includes('json') ||
    meta.name?.endsWith('.cube') ||
    meta.name?.endsWith('.xmp') ||
    meta.name?.endsWith('.json')
  ) {
    text = await blob.text();
  }

  return { text, blob, name: meta.name || 'download' };
}

/**
 * Delete a file from Google Drive
 */
export async function deleteDriveFile(fileId: string, accessToken: string): Promise<boolean> {
  const res = await fetch(`https://www.googleapis.com/drive/v3/files/${fileId}`, {
    method: 'DELETE',
    headers: { Authorization: `Bearer ${accessToken}` },
  });

  if (!res.ok && res.status !== 204) {
    throw new Error(`Failed to delete Google Drive file: ${res.statusText}`);
  }

  return true;
}

/**
 * Retrieve user storage info and profile details
 */
export async function getDriveStorageInfo(accessToken: string): Promise<DriveStorageQuota> {
  const res = await fetch('https://www.googleapis.com/drive/v3/about?fields=storageQuota,user', {
    headers: { Authorization: `Bearer ${accessToken}` },
  });

  if (!res.ok) {
    throw new Error(`Failed to fetch Drive quota: ${res.statusText}`);
  }

  const data = await res.json();
  return {
    limit: data.storageQuota?.limit,
    usage: data.storageQuota?.usage,
    usageInDrive: data.storageQuota?.usageInDrive,
    user: data.user,
  };
}
